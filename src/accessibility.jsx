function translateText(value, language) {
  if (typeof value !== 'string') return value
  if (language !== 'hi') return value
  const trimmed = value.trim()
  if (translations[trimmed]) return value.replace(trimmed, translations[trimmed])
  const countMatch = trimmed.match(/^(\d+) books$/)
  if (countMatch) return value.replace(trimmed, `${countMatch[1]} किताबें`)
  const editionsMatch = trimmed.match(/^(\d+) free reading editions$/)
  if (editionsMatch) return value.replace(trimmed, `${editionsMatch[1]} निःशुल्क पठन संस्करण`)
  const showingMatch = trimmed.match(/^Showing (\d+) of (\d+) books$/)
  if (showingMatch) return value.replace(trimmed, `${showingMatch[2]} में से ${showingMatch[1]} किताबें`)
  const percentMatch = trimmed.match(/^(\d+)% read$/)
  if (percentMatch) return value.replace(trimmed, `${percentMatch[1]}% पढ़ा`)
  const amountMatch = trimmed.match(/^Continue to pay (₹[\d,.]+)$/)
  if (amountMatch) return value.replace(trimmed, `₹${amountMatch[1].slice(1)} का भुगतान जारी रखें`)
  return value
}

function readStoredValue(key, fallback) {
  try {
    return localStorage.getItem(key) ?? fallback
  } catch (error) {
    console.error('Could not read accessibility preference:', error)
    return fallback
  }
}

export function AccessibilityProvider({ children }) {
  const [language, setLanguage] = useState(() => readStoredValue(LANGUAGE_KEY, 'en') === 'hi' ? 'hi' : 'en')
  const [highContrast, setHighContrast] = useState(() => readStoredValue(CONTRAST_KEY, 'false') === 'true')
  const [textSize, setTextSize] = useState(() => {
    const stored = Number(readStoredValue(TEXT_SIZE_KEY, '1'))
    return [1, 1.1, 1.2].includes(stored) ? stored : 1
  })
  const value = useMemo(() => ({
    language,
    setLanguage,
    highContrast,
    setHighContrast,
    textSize,
    setTextSize,
    t: (text) => translateText(text, language)
  }), [highContrast, language, textSize])

  useEffect(() => {
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en'
    document.documentElement.classList.toggle('high-contrast', highContrast)
    document.documentElement.style.setProperty('--accessibility-zoom', String(textSize))
    try {
      localStorage.setItem(LANGUAGE_KEY, language)
      localStorage.setItem(CONTRAST_KEY, String(highContrast))
      localStorage.setItem(TEXT_SIZE_KEY, String(textSize))
    } catch (error) {
      console.error('Could not save accessibility preferences:', error)
    }
  }, [highContrast, language, textSize])

  return <AccessibilityContext.Provider value={value}>{children}</AccessibilityContext.Provider>
}

export function useAccessibility() {
  const context = useContext(AccessibilityContext)
  if (!context) throw new Error('useAccessibility must be used within AccessibilityProvider.')
  return context
}
